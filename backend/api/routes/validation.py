@router.post("/runs")
def create_run(req: BenchmarkRunRequest, request: Request, db: Session = Depends(get_db)) -> dict:
    started = time.perf_counter()
    result = run_benchmarks_fresh(req.seed)
    digest = _digest(result)
    created = datetime.now(timezone.utc).isoformat()
    user = getattr(request.state, "current_user", None)
    row = ValidationRun(id=str(uuid.uuid4()), owner_id=user.id if user else None, suite="core-microarchitecture-benchmarks",
                        seed=req.seed, created_at=created, duration_ms=round((time.perf_counter()-started)*1000, 3),
                        result_sha256=digest, manifest_json=json.dumps(_manifest(req.seed, digest), sort_keys=True),
                        result_json=json.dumps(result, separators=(",", ":"), allow_nan=False))
    db.add(row); db.commit(); db.refresh(row)
    return _serialize(row, include_result=True)


@router.get("/runs")
def list_runs(request: Request, limit: int = 30, db: Session = Depends(get_db)) -> list[dict]:
    rows = db.scalars(_visible_query(db, request).limit(max(1, min(limit, 100)))).all()
    return [_serialize(row) for row in rows]


@router.get("/runs/{run_id}")
def get_run(run_id: str, request: Request, db: Session = Depends(get_db)) -> dict:
    row = db.scalar(_visible_query(db, request).where(ValidationRun.id == run_id))
    if row is None:
        raise HTTPException(404, detail={"code": "not_found", "message": "Validation run not found", "errors": []})
    return _serialize(row, include_result=True)


@router.post("/runs/{run_id}/reproduce")
def reproduce_run(run_id: str, request: Request, db: Session = Depends(get_db)) -> dict:
    row = db.scalar(_visible_query(db, request).where(ValidationRun.id == run_id))
    if row is None:
        raise HTTPException(404, detail={"code": "not_found", "message": "Validation run not found", "errors": []})
    replay = run_benchmarks_fresh(row.seed)
    replay_hash = _digest(replay)
    return {"original_run_id": row.id, "seed": row.seed, "original_sha256": row.result_sha256,
            "replay_sha256": replay_hash, "reproducible": replay_hash == row.result_sha256,
            "comparison": "exact JSON result hash match" if replay_hash == row.result_sha256 else "result hash mismatch",
            "replayed_at": datetime.now(timezone.utc).isoformat(), "data_source": "simulated"}
