"""Research provenance, reproducibility and statistical validation endpoints."""
import hashlib
import importlib.metadata
import json
import platform
import time
import uuid
from datetime import datetime, timezone

from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.config import VERSION
from app.database.models import ValidationRun
from app.database.session import get_db
from app.simulation.benchmarks import run_benchmarks_fresh

router = APIRouter(prefix="/validation", tags=["research-validation"])


class BenchmarkRunRequest(BaseModel):
    seed: int = Field(default=0, ge=0, le=1000)


def _canonical(value: dict) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode("utf-8")


def _digest(value: dict) -> str:
    return hashlib.sha256(_canonical(value)).hexdigest()


def _visible_query(db: Session, request: Request):
    user = getattr(request.state, "current_user", None)
    stmt = select(ValidationRun).order_by(ValidationRun.created_at.desc())
    if user is not None and user.role != "admin":
        stmt = stmt.where(ValidationRun.owner_id == user.id)
    elif user is None:
        stmt = stmt.where(ValidationRun.owner_id.is_(None))
    return stmt


def _manifest(seed: int, result_hash: str) -> dict:
    def version(name: str):
        try:
            return importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            return None
    return {
        "schema": "archex-validation-manifest/v1",
        "suite": "core-microarchitecture-benchmarks",
        "seed": seed,
        "software_version": VERSION,
        "python_version": platform.python_version(),
        "platform": platform.platform(),
        "dependencies": {"numpy": version("numpy"), "scikit-learn": version("scikit-learn"), "sqlalchemy": version("sqlalchemy")},
        "result_sha256": result_hash,
        "deterministic": True,
        "data_source": "simulated",
        "limitations": [
            "Workloads and outcomes are generated by ARCHEX simulators, not measured on physical hardware.",
            "Results are valid for comparing configurations within this simulator and its documented assumptions.",
            "Platform metadata is recorded for provenance; it does not establish hardware equivalence.",
        ],
    }


def _serialize(row: ValidationRun, include_result: bool = False) -> dict:
    out = {"id": row.id, "suite": row.suite, "seed": row.seed, "created_at": row.created_at,
           "duration_ms": row.duration_ms, "result_sha256": row.result_sha256,
           "manifest": json.loads(row.manifest_json)}
    if include_result:
        out["result"] = json.loads(row.result_json)
    return out


