LIMITATIONS = [
    "All traces are synthetic; scores describe how separable the simulator's scenarios are, not real-world detection accuracy.",
    "Anomaly scenarios are generated by this project's own pattern generators, so the models may learn generator artefacts.",
    "The isolation-forest score is an anomaly score, not a probability. Random-forest class probabilities are uncalibrated.",
    "Test traces use an independent seed range from training traces and the scaler is fitted on training data only.",
    "Near-perfect supervised scores mainly show that these synthetic scenarios are well separated; treat them as a sanity check, not a benchmark.",
    "Permutation importance is computed for the random forest only.",
]
_LOCK = threading.Lock()
_BUNDLE: dict | None = None


class ModelsNotTrained(RuntimeError):
    pass


def model_dir() -> Path:
    # os.environ first so tests and deployments can redirect at runtime; settings makes the value work from .env too.
    configured = os.environ.get("ARCHEX_MODEL_DIR") or settings.model_dir
    return Path(configured) if configured else Path(__file__).resolve().parents[3] / "data" / "models"


def _bundle_path() -> Path:
    return model_dir() / "archex_models.joblib"


def model_status() -> tuple[str, str]:
    if importlib.util.find_spec("sklearn") is None:
        return "unavailable", "scikit-learn is not installed"
    if not _bundle_path().exists() and _BUNDLE is None:
        return "unavailable", "Models not trained yet: POST /api/v1/ai/train"
    return "online", "Models loaded from disk"


def _dataset(n: int, seed0: int):
    traces = [generate_trace(sc, seed0 + i) for sc in SCENARIOS for i in range(n)]
    feats = [extract_features(t) for t in traces]
    for f in feats:
        validate_features(f)
    return feats, [t["scenario"] for t in traces]


def train_all(n_per_class: int = 300, n_test_per_class: int = 150, seed: int = 0, save: bool = True) -> dict:
    global _BUNDLE
    train_start, test_start = seed * 1_000_000, seed * 1_000_000 + 500_000
    feats_tr, y_tr = _dataset(n_per_class, train_start)
    feats_te, y_te = _dataset(n_test_per_class, test_start)
    X_tr, X_te = to_matrix(feats_tr), to_matrix(feats_te)
    scaler = fit_scaler(X_tr)  # training data only
    Xs_tr, Xs_te = scaler.transform(X_tr), scaler.transform(X_te)
    y_tr_a, y_te_a = np.array(y_tr), np.array(y_te)
    normal_tr = Xs_tr[y_tr_a == "normal"]

    det = AnomalyDetector(seed).fit(normal_tr)
    rf = build_random_forest(seed).fit(Xs_tr, y_tr)
    lr = build_logistic_regression(seed).fit(Xs_tr, y_tr)

    anom_true = y_te_a != "normal"
    labels = list(SCENARIOS)
    scores = det.score(Xs_te)
    metrics = {"isolation_forest": {"task": "binary anomaly detection (trained on normal traces only)",
                                    **binary_metrics(anom_true, scores > det.threshold, scores), "threshold": round(det.threshold, 6)}}
    for name, model in (("random_forest", rf), ("logistic_regression", lr)):
        proba = model.predict_proba(Xs_te)
        pred = model.predict(Xs_te)
        p_norm = proba[:, list(model.classes_).index("normal")]
        metrics[name] = {"task": "scenario classification (4 classes)", "multiclass": multiclass_metrics(y_te, list(pred), labels),
                         "binary": binary_metrics(anom_true, pred != "normal", 1 - p_norm)}

    perm = permutation_importance(rf, Xs_te, y_te, n_repeats=5, random_state=seed, scoring="accuracy")
    normal_raw = X_tr[y_tr_a == "normal"]
    split_payload = {"train_labels": y_tr, "test_labels": y_te,
                     "train_seed_range": [train_start, train_start + n_per_class - 1],
                     "test_seed_range": [test_start, test_start + n_test_per_class - 1]}
    split_fingerprint = hashlib.sha256(json.dumps(split_payload, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    split_manifest = {"strategy": "independent deterministic seed ranges", "train_seed_range": split_payload["train_seed_range"],
                      "test_seed_range": split_payload["test_seed_range"], "seed_ranges_disjoint": train_start + n_per_class - 1 < test_start,
                      "train_samples": len(y_tr), "test_samples": len(y_te), "class_counts_train": {k: y_tr.count(k) for k in labels},
                      "class_counts_test": {k: y_te.count(k) for k in labels}, "split_fingerprint_sha256": split_fingerprint,
                      "scaler_fit_partition": "train_only"}
    bundle = {
        "scaler": scaler, "detector": det, "rf": rf, "lr": lr, "feature_names": FEATURES, "labels": labels,
        "normal_stats": {f: {"mean": float(normal_raw[:, i].mean()), "std": float(normal_raw[:, i].std())} for i, f in enumerate(FEATURES)},
        "metrics": metrics,
        "importance": {"permutation": {f: {"mean": round(float(perm.importances_mean[i]), 5), "std": round(float(perm.importances_std[i]), 5)} for i, f in enumerate(FEATURES)},
                       "impurity": {f: round(float(v), 5) for f, v in zip(FEATURES, rf.feature_importances_)}},
        "config": {"n_per_class_train": n_per_class, "n_per_class_test": n_test_per_class, "seed": seed, "classes": labels,
                   "train_seed_range": [train_start, train_start + n_per_class - 1], "test_seed_range": [test_start, test_start + n_test_per_class - 1],
                   "n_train": len(y_tr), "n_test": len(y_te), "detector_quantile": det.quantile},
        "split_manifest": split_manifest,
        "trained_at": datetime.now(timezone.utc).isoformat(), "sklearn_version": sklearn.__version__, "limitations": LIMITATIONS,
    }
    if save:
        model_dir().mkdir(parents=True, exist_ok=True)
        joblib.dump(bundle, _bundle_path())
        (model_dir() / "metrics.json").write_text(json.dumps({k: bundle[k] for k in ("metrics", "importance", "config", "trained_at")}, indent=2))
    with _LOCK:
        _BUNDLE = bundle
    return bundle


def load_bundle() -> dict:
    global _BUNDLE
    with _LOCK:
        if _BUNDLE is None:
            if not _bundle_path().exists():
                raise ModelsNotTrained("Models are not trained. Run POST /api/v1/ai/train first.")
            _BUNDLE = joblib.load(_bundle_path())
        return _BUNDLE


def reset_cache() -> None:
    global _BUNDLE
    with _LOCK:
        _BUNDLE = None


def evaluation_report() -> dict:
    b = load_bundle()
    return {"data_source": "simulated", "trained_at": b["trained_at"], "config": b["config"], "split_manifest": b.get("split_manifest", {}), "metrics": b["metrics"], "importance": b["importance"],
            "feature_units": FEATURE_UNITS, "limitations": b["limitations"], "sklearn_version": b["sklearn_version"]}


def analyze(scenario: str, seed: int, classifier: str = "random_forest") -> dict:
    b = load_bundle()
    trace = generate_trace(scenario, seed)
    checks = validate_trace(trace)
    feats = extract_features(trace)
    validate_features(feats)
    xs = b["scaler"].transform(to_matrix([feats]))
    det: AnomalyDetector = b["detector"]
    score = float(det.score(xs)[0])
    flagged = score > det.threshold
    pct = det.percentile_vs_normal(score)
    model = b["rf" if classifier == "random_forest" else "lr"]
    proba = dict(zip(model.classes_, (float(p) for p in model.predict_proba(xs)[0])))
    pred = max(proba, key=proba.get)
    return {
        "data_source": "simulated", "created_at": datetime.now(timezone.utc).isoformat(),
        "trace": {"generated_scenario": scenario, "seed": seed, "accesses": len(trace["addresses"]), "branches": len(trace["branches"])},
        "validation": {"ok": True, "checks": checks + ["all 9 features finite"]},
        "features": {f: round(float(v), 6) for f, v in feats.items()}, "feature_units": FEATURE_UNITS,
        "detection": {"model": "isolation_forest", "classification": "anomalous" if flagged else "normal", "anomaly_score": round(score, 6),
                      "threshold": round(det.threshold, 6), "percentile_vs_normal_training": round(pct, 4),
                      "score_note": "Anomaly score from an Isolation Forest. Not a probability and not calibrated."},
        "risk": {"level": "low" if not flagged else "moderate" if pct < 0.995 else "high",
                 "basis": "Score percentile among normal training traces: flagged above the 95th, high above the 99.5th."},
        "classification": {"model": classifier, "predicted_scenario": pred, "predicted_label": LABELS[pred],
                           "class_probabilities": {k: round(v, 4) for k, v in proba.items()},
                           "probability_note": "Model-estimated class probabilities from the trained model; uncalibrated."},
        "explanation": {"detector": explain_detector(b, feats, xs), "classifier": explain_classifier(b, feats, xs, classifier)},
        "model_trained_at": b["trained_at"],
    }
